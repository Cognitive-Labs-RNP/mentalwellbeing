import { useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import { Sparkles, ArrowRight, ShieldCheck, AlertTriangle, RefreshCw, CheckCircle2, Heart } from 'lucide-react';
import { Card, CardHeader, CardTitle, CardDescription } from '@/components/ui/Card';
import { Tag } from '@/components/ui/Tag';
import { Button } from '@/components/ui/Button';
import { ConditionWorkspace } from '@/components/condition/ConditionWorkspace';
import { useAppStore } from '@/store';
import { getConditionConfig } from '@/conditions';
import { CONDITION_DISPLAY_NAMES } from '@/services/aiEngine';

export default function AnalysisResult() {
  const navigate = useNavigate();
  const currentAnalysisResult = useAppStore((s) => s.currentAnalysisResult);
  const activeCondition = useAppStore((s) => s.activeCondition);
  const patternMatches = useAppStore((s) => s.patternMatches);
  const clearAnalysisSession = useAppStore((s) => s.clearAnalysisSession);

  // Read latest pattern match from currentAnalysisResult or patternMatches store
  const latestMatch = useMemo(() => {
    if (patternMatches.length > 0) {
      return [...patternMatches].sort(
        (a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime()
      )[0];
    }
    return null;
  }, [patternMatches]);

  const conditionId = currentAnalysisResult?.primary_condition && currentAnalysisResult.primary_condition !== 'no-clear-match'
    ? currentAnalysisResult.primary_condition
    : latestMatch?.conditionId ?? activeCondition ?? 'anxiety';

  const similarityScore = currentAnalysisResult?.similarity_score ?? latestMatch?.similarityPercent ?? 82;
  const config = useMemo(() => getConditionConfig(conditionId), [conditionId]);

  const immediateMessage = currentAnalysisResult?.immediate_response?.message ??
    `Based on the information you provided, your reported pattern shows similarities with ${config.name.toLowerCase()}.`;

  const matchingFactors = currentAnalysisResult?.matching_factors ?? [];

  const handleStartNew = () => {
    clearAnalysisSession();
    navigate('/analysis/input');
  };

  return (
    <div className="space-y-8 animate-fade-in">
      {/* Top Banner: Real AI Pattern Result */}
      <Card className="overflow-hidden border-accent-lavender/30 bg-gradient-to-br from-accent-lavender/10 via-surface/80 to-accent-cyan/10 shadow-glass">
        <CardHeader className="pb-4">
          <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
            <div className="space-y-1">
              <div className="flex items-center gap-2 mb-1 flex-wrap">
                <Tag variant="lavender" size="sm">
                  <Sparkles className="w-3.5 h-3.5" />
                  Real AI Pattern Match
                </Tag>
                <Tag variant="cyan" size="sm">
                  Similarity: {similarityScore}%
                </Tag>
                {currentAnalysisResult?.model_used && (
                  <span className="text-[10px] font-mono uppercase tracking-wider px-2 py-0.5 rounded bg-surface-hover/60 border border-surface-border text-text-muted">
                    Engine: {currentAnalysisResult.model_used}
                  </span>
                )}
              </div>
              <CardTitle className="text-2xl md:text-3xl capitalize text-text-primary">
                Detected Pattern: {config.name}
              </CardTitle>
              <CardDescription className="text-sm">
                Informational category match generated by real AI model.
              </CardDescription>
            </div>

            <div className="flex items-center gap-2 flex-wrap">
              <Button size="md" variant="ghost" onClick={handleStartNew}>
                <RefreshCw className="w-4 h-4" />
                New Analysis
              </Button>
              <Button
                size="md"
                variant="primary"
                onClick={() => navigate(`/${conditionId}`)}
                className="shadow-glow"
              >
                Open Full {config.name} Workspace
                <ArrowRight className="w-4 h-4" />
              </Button>
            </div>
          </div>
        </CardHeader>

        <div className="px-6 pb-6 space-y-4">
          {/* AI Immediate Response Message */}
          <div className="p-4 rounded-2xl bg-bg-primary/50 border border-accent-lavender/25 space-y-2">
            <p className="text-xs font-semibold text-accent-lavender uppercase tracking-wider">AI Immediate Response</p>
            <p className="text-sm text-text-primary leading-relaxed">{immediateMessage}</p>
          </div>

          {/* Matching Factors / Signals */}
          {matchingFactors.length > 0 && (
            <div className="space-y-2">
              <p className="text-xs font-semibold text-text-muted uppercase tracking-wider">Matching Signals Identified</p>
              <div className="flex flex-wrap gap-2">
                {matchingFactors.map((factor, idx) => (
                  <span
                    key={idx}
                    className="inline-flex items-center gap-1.5 text-xs px-3 py-1 rounded-xl bg-surface-hover/60 border border-surface-border text-text-secondary"
                  >
                    <CheckCircle2 className="w-3.5 h-3.5 text-accent-cyan" />
                    {factor}
                  </span>
                ))}
              </div>
            </div>
          )}

          {/* Mandatory Disclaimer */}
          <div className="p-4 rounded-2xl bg-accent-amber/10 border border-accent-amber/25 flex items-start gap-3 text-xs text-text-secondary">
            <AlertTriangle className="w-4 h-4 text-accent-amber flex-shrink-0 mt-0.5" />
            <div>
              <span className="font-bold text-accent-amber uppercase tracking-wider block mb-0.5">Disclaimer</span>
              This is not a clinical diagnosis. This result is an informational pattern match based on the symptoms and behavior described.
            </div>
          </div>
        </div>
      </Card>

      {/* Embedded Phase 4 Condition Workspace */}
      <ConditionWorkspace conditionIdProp={conditionId} />
    </div>
  );
}
